import assert from 'node:assert/strict';
const base=process.env.TEST_URL||'http://127.0.0.1:8787';
if(!['127.0.0.1','localhost'].includes(new URL(base).hostname))throw Error('Integration tests are restricted to a local preview.');
const stamp=Date.now();
const actors=Object.fromEntries(['owner','admin','member','viewer','outsider'].map(role=>[role,{id:`test-${role}-${stamp}`,email:`${role}-${stamp}@example.test`}]));
let checks=0;
async function call(actor,body,status=200,origin=base){const a=actors[actor];const r=await fetch(base+'/api/workspace',{method:body?'POST':'GET',headers:{...(a?{'oai-authenticated-user-id':a.id,'oai-authenticated-user-email':a.email}:{}),Origin:origin,'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});const d=await r.json();assert.equal(r.status,status,`${actor} ${body?.action||'read'}: ${JSON.stringify(d)}`);checks++;return d;}
await call('anonymous',null,401);
const {id:projectId}=await call('owner',{action:'createProject',name:'Local API verification',key:'QA',description:'Local test data only',color:'purple'});
await call('owner',{action:'invite',projectId,email:actors.viewer.email,role:'viewer'});
await call('owner',{action:'invite',projectId,email:actors.member.email,role:'member'});
await call('owner',{action:'invite',projectId,email:actors.admin.email,role:'admin'});
const viewer=await call('viewer',null);assert(viewer.projects.some(p=>p.id===projectId));checks++;
const mine=await call('owner',null);const ownerMembership=mine.members.find(m=>m.projectId===projectId&&m.role==='owner');
const outsider=await call('outsider',null);assert(!outsider.projects.some(p=>p.id===projectId));checks++;
const issue={action:'createIssue',projectId,title:'Verify authorization',description:'',status:'To do',priority:'Medium',label:'Task',assignee:''};
await call('viewer',issue,403);
await call('outsider',issue,403);
await call('member',null);
await call('member',issue);
await call('member',{action:'invite',projectId,email:'no-access@example.test',role:'viewer'},403);
await call('admin',null);
await call('admin',{action:'changeRole',projectId,memberId:ownerMembership.id,role:'viewer'},403);
await call('owner',{action:'changeRole',projectId,memberId:ownerMembership.id,role:'viewer'},403);
await call('admin',{action:'invite',projectId,email:'no-admin@example.test',role:'admin'},403);
await call('owner',{...issue,assignee:'not-a-member'},400);
await call('owner',{...issue,status:'Invalid'},400);
await call('owner',issue,403,'https://untrusted.example');
await call('owner',{action:'createProject',name:'Invalid key',key:'!bad',color:'blue'},400);
const results=await Promise.all([call('owner',issue),call('owner',issue),call('owner',issue)]);
const final=await call('owner',null);const numbers=final.issues.filter(i=>i.projectId===projectId).map(i=>i.number);assert.equal(new Set(numbers).size,numbers.length);checks++;
console.log(`API integration: ${checks} checks passed (auth, isolation, roles, validation, origin checks, concurrent issue numbering).`);
